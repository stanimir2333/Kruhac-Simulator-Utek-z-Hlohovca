// src/fx/grade.js — filmické farebné ladenie (GTA V štýl): teplé svetlá,
// studené tiene, jemný kontrast, saturácia a vineta. Beží v display priestore
// (po OutputPass), takže pracuje s výsledným sRGB obrazom.
export const GradeShader = {
  uniforms: {
    tDiffuse: { value: null },
    uStrength: { value: 1.0 },
    uVignette: { value: 0.35 },
    uResolution: { value: { x: 1, y: 1 } },
  },
  vertexShader: [
    'varying vec2 vUv;',
    'void main(){',
    '  vUv = uv;',
    '  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);',
    '}',
  ].join('\n'),
  fragmentShader: [
    'varying vec2 vUv;',
    'uniform sampler2D tDiffuse;',
    'uniform float uStrength;',
    'uniform float uVignette;',
    'uniform vec2 uResolution;',
    'void main(){',
    '  vec4 c = texture2D(tDiffuse, vUv);',
    '  vec3 col = c.rgb;',
    '  // jemný split-tone: studené tiene, teplé svetlá',
    '  float lum = dot(col, vec3(0.299, 0.587, 0.114));',
    '  vec3 cool = vec3(0.96, 0.99, 1.06);',
    '  vec3 warm = vec3(1.05, 1.02, 0.95);',
    '  vec3 tone = mix(cool, warm, smoothstep(0.25, 0.75, lum));',
    '  col *= mix(vec3(1.0), tone, 0.10 * uStrength);',
    '  // S-krivka kontrast',
    '  col = (col - 0.5) * (1.12 * uStrength + (1.0 - uStrength)) + 0.5;',
    '  // saturácia',
    '  float g = dot(col, vec3(0.299, 0.587, 0.114));',
    '  col = mix(vec3(g), col, 1.0 - 0.05 * uStrength);',
    '  // jemný lift čiernych (žiadny clipping)',
    '  col = col * 0.97 + 0.018;',
    '  // vineta',
    '  vec2 p = vUv - 0.5;',
    '  p.x *= uResolution.x / max(uResolution.y, 1.0);',
    '  float vig = smoothstep(0.95, 0.35, length(p) * 1.35);',
    '  col *= mix(1.0, vig, uVignette * uStrength);',
    '  gl_FragColor = vec4(clamp(col, 0.0, 1.0), c.a);',
    '}',
  ].join('\n'),
};
